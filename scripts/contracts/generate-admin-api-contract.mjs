import { spawnSync } from 'node:child_process'
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const contractRoot = resolve(root, 'contracts/admin-api/v2')
const output = resolve(contractRoot, 'openapi.json')
const temporary = `${output}.tmp`

await mkdir(contractRoot, { recursive: true })
const cargo = spawnSync(
  'cargo',
  ['run', '--quiet', '-p', 'relay-admin-api', '--bin', 'export_admin_openapi'],
  { cwd: root, encoding: 'utf8' },
)
if (cargo.status !== 0) {
  process.stderr.write(cargo.stderr ?? '')
  process.exit(cargo.status ?? 1)
}
const document = JSON.parse(cargo.stdout)
if (document.openapi !== '3.1.0') throw new Error('Rust exporter did not emit OpenAPI 3.1.0')
if (document.info?.version !== '2.0.0') throw new Error('Rust exporter did not emit Admin API v2')
await writeFile(temporary, `${JSON.stringify(document, null, 2)}\n`, 'utf8')
await rename(temporary, output)

const pnpm = process.platform === 'win32'
  ? spawnSync(
      process.env.ComSpec ?? 'cmd.exe',
      ['/d', '/s', '/c', 'corepack pnpm@11.10.0 --filter @promptdock/relay-admin-api-generated generate'],
      { cwd: root, stdio: 'inherit', windowsHide: true },
    )
  : spawnSync(
      'corepack',
      ['pnpm@11.10.0', '--filter', '@promptdock/relay-admin-api-generated', 'generate'],
      { cwd: root, stdio: 'inherit' },
    )
if (pnpm.error) throw pnpm.error
if (pnpm.status !== 0) process.exit(pnpm.status ?? 1)

const generatedIndex = resolve(root, 'packages/admin-api-contract/src/generated/index.ts')
if (!(await readFile(generatedIndex, 'utf8')).includes('auto-generated by @hey-api/openapi-ts')) {
  throw new Error('Hey API output is missing its generated marker')
}

const zodPath = resolve(root, 'packages/admin-api-contract/src/generated/zod.gen.ts')
const generatedZod = await readFile(zodPath, 'utf8')
function enforceStrictObjects(source) {
  const starts = []
  let cursor = 0
  while ((cursor = source.indexOf('z.object({', cursor)) !== -1) {
    starts.push(cursor)
    cursor += 'z.object({'.length
  }
  let result = source
  let inserted = 0
  for (const originalStart of starts) {
    const start = originalStart + inserted * '.strict()'.length
    let depth = 0
    let quote = null
    let escaped = false
    let end = -1
    for (let index = start + 'z.object'.length; index < result.length; index += 1) {
      const character = result[index]
      if (quote) {
        if (escaped) escaped = false
        else if (character === '\\') escaped = true
        else if (character === quote) quote = null
        continue
      }
      if (character === "'" || character === '"' || character === '`') {
        quote = character
      } else if (character === '(') {
        depth += 1
      } else if (character === ')') {
        depth -= 1
        if (depth === 0) {
          end = index + 1
          break
        }
      }
    }
    if (end === -1) throw new Error('Could not find the end of a generated Zod object schema')
    if (!result.startsWith('.strict()', end)) {
      result = `${result.slice(0, end)}.strict()${result.slice(end)}`
      inserted += 1
    }
  }
  return { count: starts.length, source: result }
}
const strictResult = enforceStrictObjects(generatedZod)
const strictZod = strictResult.source
if (strictResult.count === 0 || strictZod === generatedZod) {
  throw new Error('Could not enforce strict generated Zod object schemas')
}
await writeFile(zodPath, strictZod, 'utf8')

const operations = Object.entries(document.paths).flatMap(([path, item]) =>
  Object.entries(item)
    .filter(([method, operation]) => ['get', 'post', 'delete'].includes(method) && operation?.operationId)
    .map(([method, operation]) => ({ method: method.toUpperCase(), operationId: operation.operationId, path })),
)
const routeKeys = {
  getAdminMetaV2: 'meta', getAdminOverviewV2: 'overview', listAdminDevicesV2: 'devices',
  getAdminDeviceV2: 'deviceDetail', rotateAdminDeviceV2: 'deviceRotate',
  enableAdminDeviceV2: 'deviceEnable', disableAdminDeviceV2: 'deviceDisable',
  revokeAdminDeviceV2: 'deviceRevoke', getAdminWechatStatusV2: 'wechatStatus',
  listAdminWechatEventsV2: 'wechatEvents', testAdminWechatV2: 'wechatTest',
  disconnectAdminWechatV2: 'wechatDisconnect', startAdminWechatLoginV2: 'wechatLogin',
  getAdminWechatLoginV2: 'wechatLoginSession', verifyAdminWechatLoginV2: 'wechatLoginVerify',
  listAdminDeliveriesV2: 'deliveries', listAdminInteractiveRepliesV2: 'interactiveReplies',
  listAdminInboundCommandsV2: 'inboundCommands', listAdminResultsV2: 'results',
  getAdminResultV2: 'resultDetail', revokeAdminResultV2: 'resultRevoke', getAdminSystemV2: 'system',
  runAdminRetentionV2: 'retention',
}
const routes = Object.fromEntries(
  operations
    .filter(({ operationId }) => operationId !== 'createAdminDeviceV2' && operationId !== 'cancelAdminWechatLoginV2')
    .map(({ operationId, path }) => [routeKeys[operationId], path.replace('/admin/api/v2', '')]),
)
if (Object.keys(routes).some((key) => key === 'undefined') || Object.keys(routes).length !== 23) {
  throw new Error('OpenAPI operation inventory cannot generate the stable Admin route names')
}
const routeOrder = [
  'getAdminMetaV2', 'getAdminOverviewV2', 'listAdminDevicesV2', 'createAdminDeviceV2',
  'getAdminDeviceV2', 'rotateAdminDeviceV2', 'enableAdminDeviceV2', 'disableAdminDeviceV2',
  'revokeAdminDeviceV2', 'getAdminWechatStatusV2', 'listAdminWechatEventsV2',
  'testAdminWechatV2', 'disconnectAdminWechatV2', 'startAdminWechatLoginV2',
  'getAdminWechatLoginV2', 'cancelAdminWechatLoginV2', 'verifyAdminWechatLoginV2',
  'listAdminDeliveriesV2', 'listAdminInteractiveRepliesV2', 'listAdminInboundCommandsV2',
  'listAdminResultsV2', 'getAdminResultV2', 'revokeAdminResultV2', 'getAdminSystemV2',
  'runAdminRetentionV2',
]
const operationsById = new Map(operations.map((operation) => [operation.operationId, operation]))
const routeInventory = routeOrder.map((operationId) => {
  const operation = operationsById.get(operationId)
  if (!operation) throw new Error(`OpenAPI operation is missing: ${operationId}`)
  return {
    methods: operation.method === 'GET' ? ['GET', 'HEAD'] : [operation.method],
    path: operation.path.replace('/admin/api/v2', ''),
  }
})
const routesSource = `// This file is generated from contracts/admin-api/v2/openapi.json.\n` +
  `export const ADMIN_API_MAJOR = 2 as const\n` +
  `export const ADMIN_API_BASE_PATH = '/admin/api/v2' as const\n` +
  `export const ADMIN_API_ROUTES = Object.freeze(${JSON.stringify(routes, null, 2)})\n` +
  `export const ADMIN_API_ROUTE_INVENTORY = Object.freeze(${JSON.stringify(routeInventory, null, 2)})\n`
await writeFile(resolve(root, 'packages/admin-api-contract/src/generated/routes.gen.ts'), routesSource, 'utf8')
await writeFile(
  resolve(contractRoot, 'inventories/routes-v2.json'),
  `${JSON.stringify({ schemaVersion: 2, basePath: '/admin/api/v2', routes: routeInventory }, null, 2)}\n`,
  'utf8',
)

const manifest = spawnSync(process.execPath, ['scripts/contracts/update-admin-contract-manifest.mjs'], {
  cwd: root,
  stdio: 'inherit',
})
if (manifest.status !== 0) process.exit(manifest.status ?? 1)

await rm(temporary, { force: true })
console.log('Generated Admin API v2 OpenAPI, TypeScript SDK/types/Zod, and fixture manifest.')
